-- ─────────────────────────────────────────────────────────
-- Shared chat (redesign step 1, see docs/chat-redesign-plan.md).
--
-- One thread for the household. The two adults write role = 'user'
-- messages. Eitan (the AI) writes role = 'assistant' messages from the
-- server with the service role, which bypasses RLS. A browser can never
-- forge an assistant message or post as the other adult.
--
-- Additive only: a new table, a new helper function, and the table
-- added to the realtime publication. Idempotent / safe to re-run.
-- ─────────────────────────────────────────────────────────

-- Helper: the family_members.id of the signed-in user (null if none).
-- SECURITY DEFINER for the same reason as is_adult(): reading
-- family_members from inside a policy must not re-enter its RLS.
create or replace function public.current_member_id()
returns uuid
language sql
security definer
set search_path = public
stable
as $$
  select id
  from public.family_members
  where auth_user_id = auth.uid()
  limit 1;
$$;

revoke all on function public.current_member_id() from public;
grant execute on function public.current_member_id() to authenticated;

create table if not exists public.chat_messages (
  id         uuid primary key default gen_random_uuid(),
  role       text not null check (role in ('user', 'assistant')),
  -- The adult who wrote it. Null for assistant messages.
  author_id  uuid references public.family_members(id) on delete set null,
  body       text not null check (char_length(body) between 1 and 4000),
  -- Generated by the sending device. Makes a double-tap / retry harmless,
  -- and lets the sender match the realtime echo to its optimistic bubble.
  client_id  uuid unique,
  -- Room to grow: linked task ids, calendar-button state, audio path,
  -- transcript (later steps).
  meta       jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_created_at_idx
  on public.chat_messages (created_at desc);

alter table public.chat_messages enable row level security;

-- Both adults read the whole thread.
drop policy if exists "adults_read_chat" on public.chat_messages;
create policy "adults_read_chat"
  on public.chat_messages
  for select
  using (public.is_adult());

-- An adult may only insert their OWN user messages.
drop policy if exists "adults_insert_own_chat" on public.chat_messages;
create policy "adults_insert_own_chat"
  on public.chat_messages
  for insert
  with check (
    public.is_adult()
    and role = 'user'
    and author_id = public.current_member_id()
  );

-- No update/delete policies: messages are immutable from the browser.

-- Live updates: stream inserts to both phones (Realtime honours RLS).
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'chat_messages'
  ) then
    alter publication supabase_realtime add table public.chat_messages;
  end if;
end
$$;
